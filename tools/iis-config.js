// Writes web.config so IIS can run the game server through HttpPlatformHandler.
// IIS starts `node server.js` on a private port and forwards pages and the
// WebSocket to it. Run on the PC that hosts IIS:
//
//   npm run iis-config                       (site bound to port 80)
//   npm run iis-config -- 8080               (site bound to another port)
//   npm run iis-config -- 443 https://game.example.com   (public address)
//
// See "Hosting on IIS" in the README for the one-time Windows setup.

const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "..");
const sharePort = Number(process.argv[2]) || 80;
const publicUrl = process.argv[3] || "";
const xml = (s) => s.replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;");

const config = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/iis-config.js - rerun it instead of editing by hand -->
<configuration>
  <system.webServer>
    <handlers>
      <add name="WCLKnights" path="*" verb="*" modules="httpPlatformHandler" resourceType="Unspecified" />
    </handlers>
    <httpPlatform processPath="${xml(process.execPath)}"
                  arguments="&quot;${xml(path.join(root, "server.js"))}&quot;"
                  startupTimeLimit="20"
                  stdoutLogEnabled="true"
                  stdoutLogFile="${xml(path.join(root, "logs", "node"))}">
      <environmentVariables>
        <environmentVariable name="PORT" value="%HTTP_PLATFORM_PORT%" />
        <environmentVariable name="SHARE_PORT" value="${sharePort}" />
        <environmentVariable name="PUBLIC_URL" value="${xml(publicUrl)}" />
      </environmentVariables>
    </httpPlatform>
    <webSocket enabled="true" />
  </system.webServer>
</configuration>
`;

fs.mkdirSync(path.join(root, "logs"), { recursive: true });
fs.writeFileSync(path.join(root, "web.config"), config);
console.log(`Wrote ${path.join(root, "web.config")}`);
console.log(`  node:   ${process.execPath}`);
console.log(`  links:  port ${sharePort}${publicUrl ? `, ${publicUrl}` : ""}`);
